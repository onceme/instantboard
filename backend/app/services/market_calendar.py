CLOSED_REASON_WEEKEND = "weekend"
CLOSED_REASON_HOLIDAY = "holiday"
CLOSED_REASON_OFF_HOURS = "off_hours"


def get_market_holiday_name(market: str, day: date) -> str | None:
    """Holiday name for the market on that date, or None (unknown market,
    weekday trading day, or a year outside the static table)."""
    return MARKET_HOLIDAYS.get(market, {}).get(day.isoformat())


def is_market_holiday(market: str, day: date) -> bool:
    return get_market_holiday_name(market, day) is not None


def market_closed_reason(market: str, now: datetime | None = None) -> str | None:
    """Why the market is closed, or None while it is open.

    Priority: holiday > weekend > off-hours (trading windows per
    MARKET_TRADING_HOURS). Unknown markets return None (nothing to say);
    callers deciding open/closed must check the market key themselves.
    """
    tz = MARKET_TIMEZONES.get(market)
    if tz is None:
        return None

    now = datetime.now(tz) if now is None else now.astimezone(tz)

    if is_market_holiday(market, now.date()):
        return CLOSED_REASON_HOLIDAY
    if now.weekday() >= 5:
        return CLOSED_REASON_WEEKEND

    local_time = now.time()
    trading_hours = MARKET_TRADING_HOURS.get(market, [])
    if any(open_time <= local_time <= close_time for open_time, close_time in trading_hours):
        return None
    return CLOSED_REASON_OFF_HOURS
